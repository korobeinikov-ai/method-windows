#!/bin/bash
# Базовый метод — короткие правила, которые наборы навыков автора кладут в личные инструкции Claude
# (~/.claude/CLAUDE.md) блоком между метками. Полный метод их заменяет: блок убираем, чтобы правила не задваивались.
# Запускает Claude только с «да» человека: установка блок лишь находит, личный файл человека молча не правим.
# Метка — только полная строка комментария; всё вне меток — инструкции человека, их не трогаем. Перед правкой — копия рядом; пишем поверх файла, чтобы ссылка на файл
# осталась ссылкой. Хвостовые пустые строки уходят вместе с блоком: их добавил набор. Концы строк CRLF сохраняются
# (BINMODE=3: awk читает и пишет файл как есть). Сбой — строка ⚠️ с причиной, файл человека остаётся прежним.
F="${1:-${CLAUDE_CONFIG_DIR:-$HOME/.claude}/CLAUDE.md}"  # путь можно передать первым словом
S='<!-- korobeinikov-ai-baza:start'; E='<!-- korobeinikov-ai-baza:end'
[ -f "$F" ] && grep -qF -- "$S" "$F" || exit 0
if [ "$(awk -v BINMODE=3 -v s="$S" -v e="$E" 'index($0,s){if(p)x=1;p=1} index($0,e){if(!p)x=1;p=0} END{print (x||p)?"no":"yes"}' "$F")" != yes ]; then
  echo "⚠️ БАЗОВЫЙ МЕТОД: метки блока в $F сломаны — не трогаю → скажи человеку одной строкой и предложи убрать блок вместе"
  exit 0
fi
[ -w "$F" ] || { echo "⚠️ БАЗОВЫЙ МЕТОД: нет прав на запись в $F — блок не убран, работе не мешает"; exit 0; }
B="$F.bak-korobeinikov-$(date +%Y%m%d-%H%M%S)"; [ -e "$B" ] && B="$B-$$"
T=$(mktemp) && cp "$F" "$B" \
  && awk -v BINMODE=3 -v s="$S" -v e="$E" 'index($0,s){p=1;next} p&&index($0,e){p=0;next} p{next}
       /^[[:space:]]*$/{q=q $0 "\n"; next} {printf "%s", q; q=""; print}' "$F" > "$T" && cat "$T" > "$F" \
  && echo "✅ БАЗОВЫЙ МЕТОД из прежнего набора убран: его заменяет полный (копия прежнего файла: $B)" \
  || echo "⚠️ БАЗОВЫЙ МЕТОД: убрать не вышло, работе не мешает; если $F испорчен — прежний лежит в $B"
rm -f "$T"
exit 0
